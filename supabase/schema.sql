-- ============================================================================
-- Iron Pulse — Gym Management
-- Supabase / PostgreSQL schema
--
-- Run this first in Supabase Studio → SQL Editor (or `supabase db push`).
-- Then run supabase/seed.sql for a demo roster.
--
-- Notes:
--   * UUIDs are not used; integer identity keys keep the existing app/API shape.
--   * RLS is enabled on every table with no policies, so the public anon key
--     cannot read or write anything. Connect the API with the Postgres role
--     (or service_role) which bypasses RLS.
--   * `subscriptions_no_overlap` enforces one non-overlapping active/frozen
--     membership per member at the database level.
-- ============================================================================

