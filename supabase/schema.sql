create table if not exists public.subscriptions (
  id               integer generated by default as identity primary key,
  member_id        integer not null references public.members (id) on delete cascade,
  plan_id          integer not null references public.plans (id) on delete restrict,
  start_date       date not null,
  end_date         date not null,
  status           public.subscription_status not null default 'active',
  price_at_purchase numeric(10, 2) not null check (price_at_purchase >= 0),
  discount         numeric(10, 2) not null default 0 check (discount >= 0),
  final_amount     numeric(10, 2) not null check (final_amount >= 0),
  frozen_at        timestamptz,
  notes            text,
  created_by       integer references public.users (id) on delete set null,
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now(),
  constraint subscriptions_dates_valid check (end_date >= start_date),
  constraint subscriptions_discount_within_price check (discount <= price_at_purchase),
  constraint subscriptions_amount_matches check (final_amount = round(price_at_purchase - discount, 2))
);
create index if not exists subscriptions_member_idx on public.subscriptions (member_id, end_date);
create index if not exists subscriptions_status_idx on public.subscriptions (status, end_date);
create index if not exists subscriptions_plan_idx on public.subscriptions (plan_id);

-- One non-overlapping active/frozen term per member (upcoming renewals are fine
-- as long as they start after the current term ends).
do $$ begin
  if not exists (
    select 1
      from pg_constraint
     where conname = 'subscriptions_no_overlap'
       and conrelid = 'public.subscriptions'::regclass
  ) then
    alter table public.subscriptions
      add constraint subscriptions_no_overlap
      exclude using gist (
        member_id with =,
        daterange(start_date, end_date, '[]') with &&
      ) where (status in ('active', 'frozen'));
  end if;
end $$;

