create table if not exists public.users (
  id            integer generated by default as identity primary key,
  name          text not null,
  email         text not null,
  password_hash text not null,
  role          public.user_role not null default 'receptionist',
  is_active     boolean not null default true,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now(),
  constraint users_email_unique unique (email),
  constraint users_email_lowercase check (email = lower(email)),
  constraint users_name_not_blank check (length(trim(name)) > 0)
);
create index if not exists users_role_idx on public.users (role);

create table if not exists public.members (
  id                 integer generated by default as identity primary key,
  member_code        text not null unique,
  first_name         text not null,
  last_name          text not null,
  email              text,
  phone              text not null,
  gender             text check (gender in ('male', 'female', 'other')),
  dob                date,
  address            text,
  photo_url          text,
  emergency_contact  text,
  join_date          date not null default current_date,
  status             public.member_status not null default 'active',
  notes              text,
  deleted_at         timestamptz,
  created_at         timestamptz not null default now(),
  updated_at         timestamptz not null default now(),
  constraint members_name_not_blank check (length(trim(first_name)) > 0 and length(trim(last_name)) > 0),
  constraint members_phone_not_blank check (length(trim(phone)) > 0)
);
create index if not exists members_phone_idx on public.members (phone);
create index if not exists members_status_idx on public.members (status);
create index if not exists members_join_date_idx on public.members (join_date);
create index if not exists members_name_idx on public.members (last_name, first_name);
create index if not exists members_email_idx on public.members (lower(email));

create table if not exists public.plans (
  id            integer generated by default as identity primary key,
  name          text not null,
  duration_days integer not null check (duration_days between 1 and 3650),
  price         numeric(10, 2) not null check (price >= 0),
  description   text,
  is_active     boolean not null default true,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now(),
  constraint plans_name_unique unique (name)
