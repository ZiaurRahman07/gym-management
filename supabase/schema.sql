-- ---------------------------------------------------------------- expiry jobs

-- Marks lapsed terms as expired. Returns the number of rows changed.
create or replace function public.expire_memberships()
returns integer
language sql
as $$
  with changed as (
    update public.subscriptions
       set status = 'expired'
     where status = 'active'
       and end_date < current_date
    returning 1
  )
  select count(*)::integer from changed;
$$;

-- Creates in-app alerts for the configured lead day plus 7/3/1-day milestones.
-- Safe to re-run: notifications are unique per (subscription, type).
create or replace function public.generate_expiry_alerts()
returns integer
language plpgsql
as $$
declare
  lead_days integer := 7;
  created integer := 0;
begin
  select coalesce(nullif(value, '')::integer, 7)
    into lead_days
    from public.settings
   where key = 'alert_lead_days';

  if lead_days is null then
    lead_days := 7;
  end if;

  with candidates as (
    select s.id as subscription_id,
           s.member_id,
           s.end_date,
           (s.end_date - current_date) as days_left,
           m.first_name,
           m.last_name
      from public.subscriptions s
      join public.members m on m.id = s.member_id
     where s.status = 'active'
       and m.deleted_at is null
       and m.status = 'active'
       and (s.end_date - current_date) in (lead_days, 7, 3, 1)
  ), inserted as (
    insert into public.notifications (member_id, subscription_id, type, title, body)
    select c.member_id,
           c.subscription_id,
           'expiry_' || c.days_left,
           case
             when c.days_left = lead_days then 'Membership renewal due'
             when c.days_left = 1 then 'Membership expires tomorrow'
             else 'Membership expires in ' || c.days_left || ' days'
           end,
           format('%s %s''s membership ends on %s.', c.first_name, c.last_name, to_char(c.end_date, 'YYYY-MM-DD'))
      from candidates c
    on conflict (subscription_id, type) do nothing
    returning 1
  )
  select count(*)::integer into created from inserted;

  return created;
end;
$$;

-- Convenience wrapper you can call from cron or the API.
create or replace function public.run_expiry_job()
returns jsonb
language plpgsql
as $$
declare
  expired integer;
  alerts integer;
begin
  expired := public.expire_memberships();
  alerts := public.generate_expiry_alerts();
  return jsonb_build_object('expired', expired, 'alerts', alerts);
end;
$$;

-- ---------------------------------------------------------------- reporting view

create or replace view public.member_overview
with (security_invoker = true) as
select
  m.id,
  m.member_code,
  m.first_name,
  m.last_name,
  m.email,
  m.phone,
  m.gender,
  m.join_date,
  m.status as member_status,
  s.id as subscription_id,
  s.start_date as subscription_start,
  s.end_date as subscription_end,
  s.status as subscription_status,
  p.id as plan_id,
  p.name as plan_name,
  case
    when m.status <> 'active' then m.status::text
    when s.id is null then 'none'
    when s.status = 'frozen' then 'frozen'
    when s.status = 'cancelled' then 'cancelled'
    when s.end_date < current_date then 'expired'
    else 'active'
  end as membership_status,
  (s.end_date - current_date) as days_left
from public.members m
left join lateral (
  select s2.*
    from public.subscriptions s2
   where s2.member_id = m.id
   order by (s2.status = 'active') desc, s2.end_date desc, s2.id desc
   limit 1
) s on true
left join public.plans p on p.id = s.plan_id
where m.deleted_at is null;

